/**
 * Generate unique index numbers formatted according to WASSCE/GES format:
 * e.g., 042260001 for Form 1, 042265001 for Form 2 (2026/2027 Academic Year)
 */
export function getAllStudents(): Student[] {
  const list: Student[] = [];
  let globalCount = 1;

  FORM1_CLASSES.forEach((cls) => {
    cls.students.forEach((name, idx) => {
      const paddedId = String(globalCount).padStart(4, '0');
      list.push({
        id: `std-f1-${cls.key}-${idx + 1}`,
        indexNumber: `04226${paddedId}`,
        name: name.trim(),
        form: 'form1',
        classKey: cls.key,
        className: cls.name,
        program: cls.program,
        admissionYear: 2026,
      });
      globalCount++;
    });
  });

  let f2Count = 1;
  FORM2_CLASSES.forEach((cls) => {
    cls.students.forEach((name, idx) => {
      const paddedId = String(5000 + f2Count).padStart(4, '0');
      list.push({
        id: `std-f2-${cls.key}-${idx + 1}`,
        indexNumber: `04226${paddedId}`,
        name: name.trim(),
        form: 'form2',
        classKey: cls.key,
        className: cls.name,
        program: cls.program,
        admissionYear: 2026,
      });
      f2Count++;
    });
  });

  return list;
}

export function calculateGrade(score: number): {
  letter: 'A' | 'B' | 'C' | 'D' | 'F';
  waecGrade: 'A1' | 'B2' | 'B3' | 'C4' | 'C5' | 'C6' | 'D7' | 'E8' | 'F9';
  gradePoint: number;
  remarks: string;
} {
  const rounded = Math.round(score);
  if (rounded >= 80) return { letter: 'A', waecGrade: 'A1', gradePoint: 4.0, remarks: 'Excellent' };
  if (rounded >= 75) return { letter: 'B', waecGrade: 'B2', gradePoint: 3.5, remarks: 'Very Good' };
  if (rounded >= 70) return { letter: 'B', waecGrade: 'B3', gradePoint: 3.0, remarks: 'Good' };
  if (rounded >= 65) return { letter: 'C', waecGrade: 'C4', gradePoint: 2.5, remarks: 'Credit' };
  if (rounded >= 60) return { letter: 'C', waecGrade: 'C5', gradePoint: 2.0, remarks: 'Credit' };
  if (rounded >= 50) return { letter: 'D', waecGrade: 'C6', gradePoint: 1.5, remarks: 'Pass' };
  if (rounded >= 45) return { letter: 'D', waecGrade: 'D7', gradePoint: 1.0, remarks: 'Weak Pass' };
  if (rounded >= 40) return { letter: 'D', waecGrade: 'E8', gradePoint: 0.5, remarks: 'Pass' };
  return { letter: 'F', waecGrade: 'F9', gradePoint: 0.0, remarks: 'Fail' };
}
